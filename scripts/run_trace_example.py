"""Write one fully linked recommendation trace for review.

The example uses the deterministic synthetic provider so it runs offline and
does not depend on cached market files. It is an audit demonstration, not
evidence of investment performance.
"""

from __future__ import annotations

import json
import sys
import tempfile
from dataclasses import replace
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from intellivest.config import load_settings
from intellivest.contracts import DecisionTrace, InvestorProfile
from intellivest.data.market import SyntheticMarket
from intellivest.orchestration.orchestrator import AdvisoryEngine

ROOT = Path(__file__).resolve().parents[1]


def _profile(as_of: date) -> InvestorProfile:
    return InvestorProfile(
        investor_id="TRACE-DEMO-001",
        as_of=as_of,
        age=42,
        horizon_years=10,
        risk_tolerance=3,
        loss_tolerance_pct=0.15,
        goal="balanced_growth",
        liquidity_need="medium",
        current_holdings={"SPX": 0.30, "GOVT": 0.35, "GOLD": 0.10, "CRED": 0.25},
    )


def _fmt(value: float | None, *, percent: bool = False, digits: int = 2) -> str:
    if value is None:
        return "n/a"
    return f"{value:.{digits}%}" if percent else f"{value:.{digits}f}"


def _render(trace: DecisionTrace, profile: InvestorProfile, verified: str) -> str:
    lines = [
        "# Recommendation trace example",
        "",
        "Generated by `scripts/run_trace_example.py` using the deterministic "
        "synthetic market. It demonstrates the audit path; it is not market "
        "evidence. The real-data evaluation is in `results/evaluation.md`. The "
        "trace id, timestamp and hash are unique to each run; rerunning the "
        "script produces a new, valid audit record.",
        "",
        "The same recommendation is followed from the investor profile through "
        "agent signals, Black-Litterman views, the constrained optimizer, the "
        "blocking suitability gate and the explanation, ending at the sealed "
        "audit hash.",
        "",
        "## 1. Profile",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Investor | `{profile.investor_id}` |",
        f"| As of | {profile.as_of.isoformat()} |",
        f"| Age / horizon | {profile.age} / {profile.horizon_years:.0f} years |",
        f"| Risk tolerance | {profile.risk_tolerance} |",
        f"| Loss tolerance | {profile.loss_tolerance_pct:.0%} |",
        f"| Goal / liquidity | {profile.goal} / {profile.liquidity_need} |",
        f"| Current holdings | {json.dumps(profile.current_holdings, sort_keys=True)} |",
        f"| Binding risk class | {trace.suitability.risk_class} |",
        f"| Profile digest | `{trace.profile_digest}` |",
        "",
        "## 2. Agent signals",
        "",
        "| Agent | Signal | Subject | Direction | Strength | Confidence |",
        "|---|---|---|---|---:|---:|",
    ]
    for report in trace.agents:
        for signal in report.signals:
            lines.append(
                f"| `{report.agent}` | `{signal.name}` | `{signal.subject}` | "
                f"{signal.direction} | {signal.strength:+.2f} | {signal.confidence:.2f} |"
            )

    bl = trace.black_litterman
    lines.extend(["", "## 3. Black-Litterman views", ""])
    if bl is None:
        lines.append("No Black-Litterman section was recorded.")
    else:
        lines.extend(
            [
                f"Tau `{bl.tau}`, view shift `{bl.view_shift}`, total influence "
                f"`{bl.total_influence:.4f}` (cap `{bl.max_total_influence:.4f}`, "
                f"capped: `{bl.influence_capped}`), views `{bl.n_views}`.",
                "",
                "| Asset | Prior | View | Posterior | Confidence |",
                "|---|---:|---:|---:|---:|",
            ]
        )
        for asset in sorted(bl.views):
            confidence = bl.view_confidence.get(
                f"asset:{asset}", bl.view_confidence.get(asset)
            )
            lines.append(
                f"| `{asset}` | {_fmt(bl.prior_expected_returns.get(asset), percent=True)} | "
                f"{_fmt(bl.views.get(asset), percent=True)} | "
                f"{_fmt(bl.posterior_expected_returns.get(asset), percent=True)} | "
                f"{_fmt(confidence)} |"
            )

    optimizer = trace.optimizer
    lines.extend(
        [
            "",
            "## 4. Optimizer",
            "",
            f"Method `{optimizer.method}`; solver status `{optimizer.solver_status}`; "
            f"turnover `{optimizer.turnover:.2%}`.",
            "",
            "| Metric | Value |",
            "|---|---:|",
            f"| Expected return | {optimizer.expected_return:.2%} |",
            f"| Expected volatility | {optimizer.expected_volatility:.2%} |",
            f"| Expected Sharpe | {optimizer.expected_sharpe:.3f} |",
            f"| Risk-free rate used | {_fmt(trace.risk_free_rate, percent=True)} |",
            f"| Expected CVaR 95% | {optimizer.expected_cvar_95:.2%} |",
            f"| Binding constraints | {', '.join(optimizer.binding_constraints) or 'none'} |",
            "",
            "| Weight | Value |",
            "|---|---:|",
        ]
    )
    for ticker, weight in sorted(optimizer.weights.items(), key=lambda item: -item[1]):
        lines.append(f"| `{ticker}` | {weight:.2%} |")

    lines.extend(
        [
            "",
            "## 5. Suitability gate",
            "",
            f"Passed: **{trace.suitability.passed}**; repaired: "
            f"**{trace.suitability.repaired}**; repair iterations: "
            f"`{trace.suitability.repair_iterations}`.",
            "",
            "| Rule | Observed | Limit | Passed | Severity |",
            "|---|---:|---:|---|---|",
        ]
    )
    for check in trace.suitability.checks:
        lines.append(
            f"| `{check.rule_id}` | {check.observed} | {check.limit} | "
            f"{check.passed} | {check.severity} |"
        )
    if trace.suitability.violations:
        lines.extend(["", "Residual violations:", ""])
        lines.extend(f"- {violation}" for violation in trace.suitability.violations)

    explanation = trace.explanation
    lines.extend(
        [
            "",
            "## 6. Explanation",
            "",
            "Suitability rationale:",
            "",
        ]
    )
    lines.extend(f"- {line}" for line in explanation.suitability_rationale)
    lines.extend(
        [
            "",
            "Agent contribution weights:",
            "",
            "| Agent | Contribution |",
            "|---|---:|",
        ]
    )
    for agent, contribution in sorted(
        explanation.agent_contributions.items(), key=lambda item: -item[1]
    ):
        lines.append(f"| `{agent}` | {contribution:.2%} |")
    if explanation.counterfactual:
        lines.extend(
            [
                "",
                "Counterfactual:",
                "",
                "```json",
                json.dumps(explanation.counterfactual, indent=2, sort_keys=True),
                "```",
            ]
        )

    lines.extend(
        [
            "",
            "## 7. Audit seal",
            "",
            f"- Trace id: `{trace.trace_id}`",
            f"- Created at: `{trace.created_at.isoformat()}`",
            f"- Previous hash: `{trace.previous_hash}`",
            f"- Final hash: `{trace.hash}`",
            f"- Chain verification: `{verified}`",
            "",
            "### Recorded stage digests",
            "",
            "| Stage | Status | Input digest | Output digest |",
            "|---|---|---|---|",
        ]
    )
    for step in trace.steps:
        lines.append(
            f"| `{step.name}` | {step.status} | `{step.inputs_digest[:12]}` | "
            f"`{step.output_digest[:12]}` |"
        )
    lines.extend(
        [
            "",
            "The full trace body is stored in `results/trace_example.json`; the "
            "audit chain was verified before this example was written.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    base = load_settings()
    with tempfile.TemporaryDirectory(prefix="intellivest-trace-") as tmp:
        settings = replace(base, audits_dir=Path(tmp) / "audits")
        provider = SyntheticMarket(settings)
        profile = _profile(date.fromisoformat(settings.data_end))
        engine = AdvisoryEngine(settings, provider=provider)
        trace = engine.advise(profile)
        ok, message = engine.verify_audit_chain()
        if not ok:
            raise SystemExit(f"audit verification failed: {message}")

    results = base.results_dir
    results.mkdir(parents=True, exist_ok=True)
    (results / "trace_example.md").write_text(
        _render(trace, profile, message), encoding="utf-8"
    )
    (results / "trace_example.json").write_text(
        json.dumps(trace.model_dump(mode="json"), indent=2, default=str),
        encoding="utf-8",
    )
    print(f"wrote {results / 'trace_example.md'}")
    print(f"wrote {results / 'trace_example.json'}")
    print(f"trace hash {trace.hash}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
